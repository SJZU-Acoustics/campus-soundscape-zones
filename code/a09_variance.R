# A09 — where the variance lives; how much of the recording variance the predictors absorb; evaluator random slopes for level
# and recording-mean reliability. The companion a09b runs all four slope permutation tests.
source(file.path("code", "helpers.R"))
suppressPackageStartupMessages(library(performance))
OUT <- file.path("output", "analysis_09_variance_partitioning")
dir.create(OUT, showWarnings = FALSE, recursive = TRUE)
w <- function(x, f) write_csv(x, file.path(OUT, f))
d <- load_p35("wav"); dall <- load_p35("all")
OUTS <- c("comfort", "richness", "rating_noisiness", "rating_appropriateness")
vshare <- function(m) { v <- as.data.frame(VarCorr(m)) %>% filter(is.na(var2)) %>% select(grp, vcov); v %>% mutate(share = vcov / sum(vcov)) }

# ---- 1. four-way partition on all 990 (site, session, evaluator, recording, residual)
part <- list()
for (y in OUTS) {
  m <- lme4::lmer(as.formula(paste0(y, " ~ 1 + (1 | site) + (1 | session) + (1 | evaluator) + (1 | env_id)")), data = dall)
  part[[y]] <- vshare(m) %>% mutate(outcome = y)
}
part <- bind_rows(part); w(part, "variance_partition_990.csv")
k <- nrow(dall) / n_distinct(dall$env_id)
rel <- part %>% group_by(outcome) %>% summarise(icc1_place = sum(share[grp %in% c("site", "env_id")]), icc1_evaluator = share[grp == "evaluator"], .groups = "drop") %>% mutate(k_raters_per_recording = k, icc_k_place = k * icc1_place / (1 + (k - 1) * icc1_place))
w(rel, "recording_mean_reliability.csv")
print(part %>% select(outcome, grp, share) %>% pivot_wider(names_from = grp, values_from = share) %>% mutate(across(where(is.numeric), ~round(.x, 3))))

# ---- 2. what absorbs the recording (env) variance and the evaluator variance: a predictor ladder (666 records)
steps <- c(none = "1", level = "bk_laeq_z", level_tonality = "bk_laeq_z + tonality_z", plus_sources = "bk_laeq_z + tonality_z + src_natural + src_human + src_mechanical",
           plus_zone = "bk_laeq_z + tonality_z + src_natural + src_human + src_mechanical + zone")
lad <- list()
for (y in OUTS) for (s in names(steps)) {
  m <- fit_backbone(steps[[s]], y, d); v <- as.data.frame(VarCorr(m)) %>% filter(is.na(var2))
  lad[[paste(y, s)]] <- tibble(outcome = y, step = s, var_evaluator = v$vcov[v$grp == "evaluator"], var_env = v$vcov[v$grp == "env_id"], var_resid = v$vcov[v$grp == "Residual"],
                              r2m = r2_nakagawa(m)$R2_marginal, r2c = r2_nakagawa(m)$R2_conditional)
}
lad <- bind_rows(lad) %>% group_by(outcome) %>% mutate(env_var_explained = 1 - var_env / var_env[step == "none"]) %>% ungroup()
w(lad, "predictor_ladder_variance.csv"); print(lad %>% mutate(across(where(is.numeric), ~round(.x, 3))), n = 20, width = 150)

